/** Traduit `key` dans `lang` (repli : français, puis la clé) et remplace les {variables}. */
export function translate(lang, key, vars) {
    const text = translations[lang]?.[key] ?? translations.fr[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}
